def gate(rec: Record) -> Dict[str, bool]:
    """항목별 적용 여부. False면 위반 성립 불가 → 0 확정."""
    return {item: GATES[item].적용(rec) for item in ITEMS}


def gated_items(rec: Record) -> List[str]:
    """LLM 판정이 필요한 항목만."""
    g = gate(rec)
    return [i for i in ITEMS if g[i]]


def explain(rec: Record) -> str:
    g = gate(rec)
    out = [f"[{rec.id}] {rec.적용계약법} · {rec.업무구분} · {rec.계약방법} · {rec.낙찰방법}",
           f"  추정가격 {rec.추정가격:,}원 · 판로지원밴드 {rec.판로지원밴드}"
           f" · 지역제한기준 {_지역제한_기준금액(rec):,}원"
           f"{' · 지방소액수의' if rec.소액수의_지방 else ''}"]
    blocked = [i for i in ITEMS if not g[i]]
    out.append(f"  판정대상 {24 - len(blocked)}개 / 차단 {len(blocked)}개: {', '.join(blocked) or '없음'}")
    return "\n".join(out)
