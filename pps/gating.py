def _v22(r: Record) -> bool:
    """항목표: '계약방법 협상만 적용'."""
    return r.낙찰방법 in law.V22_적용_낙찰방법


def _v23(r: Record) -> bool:
    """항목표: '계약방법 협상 + 계약법 지방만 적용'.

    항목표 국가계약법 칸에도 '해당 없음(위반 성립 불가)'이 명시돼 있다.
    """
    return r.낙찰방법 in law.V23_적용_낙찰방법 and r.적용계약법 in law.V23_적용_계약법


