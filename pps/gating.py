"""적용조건 게이팅 — 메타데이터만으로 "위반이 성립 불가능한 항목"을 확정 0으로 만든다.

설계 원칙
  1. 게이팅은 **법 구조에서 나온 것만** 쓴다. dev 상관관계만 보고 막지 않는다.
     (dev 200건은 "평가 데이터 분포를 대표하지 않음"이 README에 명시돼 있다)
  2. 게이팅이 진짜 양성을 죽이면 회복 불가능한 재현율 손실이다.
     `tools/audit_gates.py` 로 killed_positive == 0 을 항상 확인한다.
  3. 판단이 서지 않으면 열어 둔다(적용). 닫는 쪽이 항상 더 위험하다.

각 Gate는 근거 조문을 문자열로 들고 있다 — 2차 평가 출처 명세 대응.
"""
from __future__ import annotations

