@dataclass(frozen=True)
class Gate:
    item: str
    근거: str
    설명: str
    적용: Callable[[Record], bool]   # True면 LLM 판정 대상, False면 0 확정


def _always(_: Record) -> bool:
    return True


# --------------------------------------------------------------------------- 실적제한 계열

def _v2(r: Record) -> bool:
    """고시금액 미만 제조·용역에 실적제한을 걸면 위반.

    → 추정가격이 고시금액 이상이면 실적제한이 적법하므로 v2 성립 불가.
    → 지방 소액수의(1억 이하 2인견적) 경로에서는 실적제한이 허용되므로 성립 불가.
    """
    if r.추정가격 <= 0:
        return True                       # 금액 미상 → 판단 보류, 열어 둔다
    if r.추정가격 >= law.고시금액(r.업무구분):
        return False
    if r.소액수의_지방 and r.is_수의:
        return False
    return True


def _v5(r: Record) -> bool:
    """지역제한은 기준금액 '미만'인 계약에만 허용 → 기준금액 이상인데 지역제한이면 위반.

    기준금액 미만이면 지역제한이 적법하므로 v5 성립 불가.
    """
    if r.추정가격 <= 0:
        return True
    return r.추정가격 >= _지역제한_기준금액(r)


def _v6_v7(r: Record) -> bool:
    """고시금액 '미만' 구간에서의 지역제한 방식 위반(시군구 단위 / 인접 확대).

    기준금액 이상이면 지역제한 자체가 불가 → v5 영역이지 v6·v7 영역이 아니다.
    지방 소액수의 경로는 시·군·구 제한이 허용되므로 성립 불가.
    """
    if r.추정가격 <= 0:
        return True
    if r.추정가격 >= _지역제한_기준금액(r):
        return False
    if r.소액수의_지방 and r.is_수의:
        return False
    return True


def _v8(r: Record) -> bool:
    """실적제한 + 지역제한 중복.

    국가 시행규칙 제25조제5항 — 6호(지역)는 2호(공사 특수기술)와만 중복 허용.
    지방 소액수의 경로는 예외.
    """
    if r.소액수의_지방 and r.is_수의:
        return False
    return True


def _경쟁입찰만(r: Record) -> bool:
    """중소기업자간 **경쟁**제품 4항목(v10~v13)은 수의계약에 적용되지 않는다.

    근거는 항목표가 스스로 드는 조문이다.
      v11·v12·v13 — 국가계약법 시행령 **제21조**(제한경쟁입찰에 의할 계약과 제한사항)
                    / 지방계약법 시행령 **제20조**(제한입찰에 의한 계약과 제한기준)
      v10        — 판로지원법 제9조, "중소기업자간 **경쟁**제품" 지정
    제한경쟁입찰의 제한사항 규정이므로 **입찰이 아닌 수의계약에는 걸 자격 제한 자체가 없다.**

    dev200 확인(문턱 3): 소액수의견적 35건에서 이 4항목의 정답 양성은 **0건**이고
    예측 양성은 9건(v13 8 · v10 1)이다. 게이트를 걸면 FP −9 · TP −0 · Macro +0.0091.

    2026-09-07 에 게이트 두 개가 LB 를 크게 떨어뜨린 적이 있다. 그때와 다른 점은,
    그 게이트의 축(세부품명 등록 여부)이 **어느 조문에도 없는 dev 상관**이었던 반면
    이 축은 항목표가 인용한 조문 자체에서 나온다는 것이다. 같은 축(소액수의)을
    _v2·_v6_v7·_v8 이 이미 쓰고 있다.
    """
    return not (r.is_수의 and (r.낙찰방법 or "") == "소액수의견적")


# ⚠️ 아래 두 함수는 2026-09-07 제출에서 **점수를 0.42458 → 0.31943 으로 떨어뜨렸다.**
#    dev 에서 죽인 진짜 양성이 0건이었지만 실제 평가에서는 재현율을 크게 잃었다.
#    dev 양성 19건에서 "0건 죽임"의 95% 상한은 약 15% 다 — 통계적으로 안전을 보장하지
#    못한다. 게다가 세부품명 등록 여부는 어느 조문에도 없다(= 조문이 아니라 dev 상관관계).
#    다시 켜지 말 것. 게이팅은 조문이 적용 대상을 한정할 때만 쓴다.
def _세부품명_미등록(r: Record) -> bool:
    """[사용 안 함] 중기간 경쟁제품 항목을 세부품명 등록 여부로 막았던 게이트.

    판로지원법 제9조·제7조제1항의 직접생산확인·중소기업자 제한은 조달 품목이
    중기부 고시 경쟁제품일 때 발생하는 의무다. 발주기관이 나라장터에
    `세부품명번호목록`을 등록했다면 품목을 특정해 경쟁제품 여부를 확인한 것이고,
    그 경우 의무를 누락하는 일이 사실상 없다.

    dev 200건 검증
      v10 양성 7 / v11 양성 6 / v13 양성 6 — **전부 세부품명 미등록 건**이었다.
      등록된 78건(39%)을 차단하며 죽인 진짜 양성은 0건.
    분포 확인
      등록률이 dev 39.0% vs train_unlabeled 37.6% 로 거의 같다 → dev 편중이 아니다.

    ※ v12(일반제품에 직생 요구)는 반대 방향이라 이 게이트를 쓰지 않는다.
      양성 6건 중 2건이 등록 건이었다.
    """
    return not r.세부품명번호


def _직생요구_있음(r: Record) -> bool:
    """[사용 안 함] v12 를 직생 요구 문구 존재 여부로 막았던 게이트.

    v12(일반제품에 직접생산 요구)는 직생 요구가 없으면 정의상 성립하지 않는다.

    항목명이 "일반제품 직생 제한"이므로 위반 행위 자체가 '직접생산확인을 요구한 것'이다.
    요구가 없으면 위반할 대상이 없다 — dev 상관관계가 아니라 항목 정의에서 나온다.

    dev 200건: v12 양성 6건 전부 직생 요구 문구를 포함했고, 67건(33.5%)을 차단하며
    죽인 진짜 양성은 0건.
    """
    from . import presence
    return presence.scan(r.full_text, presence.V10_직생요구).present


def _지역제한_기준금액(r: Record) -> int:
    """지역제한이 허용되는 추정가격 상한."""
    if r.is_공사:
        # 지방 시행규칙 제24조제1호 / 국가는 공사 고시금액 88억
        return law.지역제한_기준_지방_공사_종합 if r.is_지방 else law.고시금액_공사
    if r.is_지방:
        # 지방 시행규칙 제24조제2호나목 — 행안부 고시금액.
        # UNCERTAIN: 고시가 배포 패키지에 없어 국가 고시금액으로 잠정 사용. law.py 참조.
        return law.지역제한_기준_지방_물품용역
    return law.지역제한_기준_국가_물품용역


# --------------------------------------------------------------------------- 판로지원 기업규모 밴드
# 국가 시행령 제21조제1항제10호 / 지방 시행령 제20조제1항제12호
#   A(<1억)      : 소기업·소상공인·벤처·창업기업 제한 가능 → 중소기업 제한은 위반(v17)
#                                                        소기업 제한 없음이 위반(v18)
#   B(1억~고시)  : 중소기업자 제한 가능           → 소기업 제한은 위반(v15)
#                                                        중소기업 제한 없음이 위반(v16)
#   C(≥고시금액) : 기업규모 제한 불가             → 중소기업 제한은 위반(v14)

def _band(want: str) -> Callable[[Record], bool]:
    def f(r: Record) -> bool:
        if r.추정가격 <= 0:
            return True
        return r.판로지원밴드 == want
    return f


