공동_최소지분율_지방_하한 = 4.0            # 20% 감액 허용 후


def 공동_최소지분율_하한(적용계약법: str, 업무구분: str = "", 추정가격: int = 0) -> float:
    """공고가 정할 수 있는 최소지분율의 법정 하한. 이보다 낮게 정하면 v21."""
    if 적용계약법 == "지방계약법":
        return 공동_최소지분율_지방_하한
    if "공사" in (업무구분 or "") and 추정가격 >= 1000 * 억:
        return 공동_최소지분율_국가_대형공사 * 0.8
    return 공동_최소지분율_국가_하한


