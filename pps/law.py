def 고시금액(업무구분: str) -> int:
    """업무구분에 대응하는 고시금액. 공사만 88억, 나머지는 2.3억."""
    return 고시금액_공사 if "공사" in (업무구분 or "") else 고시금액_물품용역


def 판로지원_밴드(추정가격: int, 업무구분: str) -> str:
    """판로지원법상 허용되는 기업규모 제한 구간.

    반환값
      'A' : 추정가격 < 1억          — 소기업·소상공인·벤처·창업기업 제한 가능
      'B' : 1억 ≤ 추정가격 < 고시금액 — 중소기업자 제한 가능
      'C' : 추정가격 ≥ 고시금액      — 기업규모 제한 불가
    """
    상한 = 고시금액(업무구분)
    if 추정가격 < 판로지원_소기업_상한:
        return "A"
    if 추정가격 < 상한:
        return "B"
    return "C"
