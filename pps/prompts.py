def render_facts(obj: Optional[Dict[str, Any]]) -> str:
    """추출 결과 → 2단계 프롬프트에 넣을 사실표.

    비어 있는 항목도 **'없음'이라고 명시**한다. 빈 칸으로 두면 모델이
    '문서를 못 봤다'고 여겨 판단을 보류하거나 원문을 추측한다.
    """
    if not isinstance(obj, dict):
        return "[사실 추출 실패 — 이 공고는 사실표 없이 판단한다]"
    out: List[str] = ["■ 공고에서 뽑은 사실 (아래가 이 공고에 대해 확인된 전부다)"]

    lim = obj.get("참가자격제한")
    out.append("\n[참가자격에 건 제한]")
    if isinstance(lim, list) and lim:
        for e in lim:
            if not isinstance(e, dict):
                continue
            out.append(f"  · {e.get('종류','?')}: {e.get('내용','')}")
            src = (e.get("원문") or "").strip()
            if src:
                out.append(f"      원문: {src}")
    else:
        out.append("  · 없음 — 참가자격을 제한하는 문구가 공고에 없다")

    spec = obj.get("규격지정")
    out.append("\n[규격·모델명 지정]")
    if isinstance(spec, list) and spec:
        for e in spec:
            if not isinstance(e, dict):
                continue
            alt = e.get("대체허용문구")
            out.append(f"  · {e.get('모델명또는규격','')} · 대체허용문구 "
                       f"{'있음: ' + str(alt) if alt else '**없음**'}")
            src = (e.get("원문") or "").strip()
            if src:
                out.append(f"      원문: {src}")
    else:
        out.append("  · 없음 — 특정 모델명·규격을 지정한 곳이 없다")

    exc = obj.get("법정예외")
    out.append("\n[공고가 명시한 법정 예외]")
    if isinstance(exc, list) and exc:
        for e in exc:
            if isinstance(e, dict):
                out.append(f"  · {e.get('조항','')}: {(e.get('원문') or '')[:200]}")
    else:
        out.append("  · 없음")

    sch = obj.get("일정")
    if isinstance(sch, dict):
        out.append("\n[일정]")
        for k in ("공고일", "현장설명회", "입찰마감"):
            v = sch.get(k)
            out.append(f"  · {k}: {v if v else '기재 없음'}")

    jv = obj.get("공동수급")
    if isinstance(jv, dict):
        out.append("\n[공동수급]")
        out.append(f"  · 허용여부: {jv.get('허용여부') or '기재 없음'}"
                   f" · 최소지분율: {jv.get('최소지분율') or '기재 없음'}")
        src = (jv.get("원문") or "").strip()
        if src:
            out.append(f"      원문: {src}")
    return "\n".join(out)



def build_select_schema(items: Sequence[str]) -> Dict[str, Any]:
    """선택형 스키마 — 위반인 항목만 배열로 받는다. 빈 배열이 '위반 없음'이다."""
    return {
        "type": "object",
        "additionalProperties": False,
        "required": [SELECT_KEY],
        "properties": {
            SELECT_KEY: {
                "type": "array",
                "maxItems": len(items),
                "items": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": ["항목", "근거문구"],
                    "properties": {
                        "항목": {"type": "string", "enum": list(items)},
                        "근거문구": {"type": ["string", "null"], "maxLength": 600},
                    },
                },
            },
        },
    }


def build_schema(items: Sequence[str], graded: bool = False,
                 select: bool = False, dual: bool = False) -> Dict[str, Any]:
    """제약 디코딩용 JSON Schema. 요청한 항목만 포함한다.

    부재탐지 항목은 근거문구를 null 로 고정한다 — 인용할 원문이 없다.
    graded=True 면 `위반여부 0|1` 대신 `위반등급 0~3` 을 받는다.
    select=True 면 항목별 판정 대신 **위반 항목만 고르는** 배열을 받는다(§선택형 출력).
    dual=True 면 등급 **앞에** `적법근거` 를 두어 반증을 먼저 탐색시킨다(§양면 판단).
    """
    if select:
        return build_select_schema(items)
    key = GRADE_KEY if graded else BINARY_KEY
    enum = list(range(GRADE_MIN, GRADE_MAX + 1)) if graded else [0, 1]
    props: Dict[str, Any] = {}
    for v in items:
        ev = ({"type": "null"} if v in ABSENCE
              else {"type": ["string", "null"], "maxLength": 600})
        if dual and v in DUAL_ITEMS:
            # 순서가 곧 생성 순서다: 적법근거 → 등급 → 근거문구.
            props[v] = {
                "type": "object",
                "additionalProperties": False,
                "required": [LAWFUL_KEY, key, "근거문구"],
                "properties": {
                    LAWFUL_KEY: {"type": ["string", "null"], "maxLength": 80},
                    key: {"type": "integer", "enum": enum},
                    "근거문구": ev,
                },
            }
            continue
        props[v] = {
            "type": "object",
            "additionalProperties": False,
            "required": [key, "근거문구"],
            "properties": {
                key: {"type": "integer", "enum": enum},
                "근거문구": ev,
            },
        }
    return {
        "type": "object",
        "additionalProperties": False,
        "required": list(items),
        "properties": props,
    }


