    항목지시: Dict[str, str] = field(default_factory=dict)

    def 지침(self, items: Sequence[str]) -> str:
        """공통 지침 + **묻는 항목의 기준만** 이어 붙인다."""
        if not self.항목지시:
            return self.지시
        want = [i for i in self.items if i in set(items) and i in self.항목지시]
        if not want:
            return self.지시
        body = "\n".join(self.항목지시[i] for i in want)
        return (f"{self.지시}\n\n"
                f"항목별 판정 기준 — **아래에 적힌 항목만 판정한다.**\n"
                f"여기 없는 항목은 이 공고에 적용되지 않으므로, 그 항목의 기준을 "
                f"끌어와 아래 항목을 판단하지 마라.\n{body}")


